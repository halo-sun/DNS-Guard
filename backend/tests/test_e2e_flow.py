from fastapi.testclient import TestClient
from backend.app.db.init_db import init_db
from backend.app.main import app

init_db()
client = TestClient(app)


def test_complete_e2e_pipeline():
    # 1. Trigger demo ingest batch
    res_ingest = client.post("/api/v1/events/ingest/demo?count=20")
    assert res_ingest.status_code == 200
    ingest_data = res_ingest.json()
    assert ingest_data["status"] == "success"
    assert ingest_data["ingested"] > 0

    # 2. Verify events query returns items
    res_events = client.get("/api/v1/events?page=1&page_size=20")
    assert res_events.status_code == 200
    events_data = res_events.json()
    assert len(events_data["items"]) > 0
    first_evt = events_data["items"][0]
    assert "normalized_domain" in first_evt
    assert "fingerprint" in first_evt

    # 3. Verify alerts generated by detection engine
    res_alerts = client.get("/api/v1/alerts")
    assert res_alerts.status_code == 200
    alerts_data = res_alerts.json()
    assert len(alerts_data["items"]) > 0

    target_alert = alerts_data["items"][0]
    alert_id = target_alert["id"]
    assert target_alert["status"] in ["new", "investigating"]
    assert target_alert["risk_score"] > 0

    # 4. Mutate alert status to 'investigating' with analyst note
    res_patch = client.patch(
        f"/api/v1/alerts/{alert_id}",
        json={"status": "investigating", "notes": "E2E automated verification test note"},
    )
    assert res_patch.status_code == 200
    patched_data = res_patch.json()
    assert patched_data["status"] == "investigating"
    assert patched_data["notes"] == "E2E automated verification test note"

    # 5. Verify dashboard summary reflects persisted counts
    res_summary = client.get("/api/v1/dashboard/summary")
    assert res_summary.status_code == 200
    summary_data = res_summary.json()
    assert summary_data["total_queries"] >= ingest_data["ingested"]
    assert summary_data["open_alerts"] > 0

    # 6. Verify analytics endpoint returns aggregated window data
    res_analytics = client.get("/api/v1/analytics?time_range=24h")
    assert res_analytics.status_code == 200
    analytics_data = res_analytics.json()
    assert analytics_data["total_queries"] > 0

    # 7. Verify CSV export streams valid rows
    res_csv = client.get("/api/v1/exports/events.csv?limit=10")
    assert res_csv.status_code == 200
    assert "normalized_domain" in res_csv.text
